// Prints supabase/seed.sql from src/lib/db/seed-data.json (times relative to now()).
// Usage: node scripts/gen-seed-sql.mjs > supabase/seed.sql
import { readFileSync } from "node:fs";

const seed = JSON.parse(readFileSync(new URL("../src/lib/db/seed-data.json", import.meta.url), "utf8"));
const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const slugify = (name) =>
  name.toLowerCase().normalize("NFKD").replace(/[̀-ͯ]/g, "").replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 48);
const ago = (m) => `now() - interval '${m} minutes'`;

const out = ["-- Generated by scripts/gen-seed-sql.mjs. Development data only.", "begin;"];
for (const l of seed.listings) {
  out.push(
    `insert into listings (name, slug, website, category, city, tagline, status, created_at) values (${[
      q(l.name), q(slugify(l.name)), q(l.website), q(l.category), q(l.city), q(l.tagline), q(l.status), ago(l.ago),
    ].join(", ")}) on conflict (slug) do nothing;`,
  );
}
const byKey = Object.fromEntries(seed.listings.map((l) => [l.key, slugify(l.name)]));
for (const b of seed.bids) {
  const status = b.status ?? "paid";
  out.push(
    `insert into bids (listing_id, amount, status, created_at, paid_at, payment_method, payment_ref) select id, ${b.amount}, ${q(status)}, ${ago(b.ago)}, ${status === "paid" ? ago(b.ago) : "null"}, ${q(b.method ?? "seed")}, ${q(b.ref)} from listings where slug = ${q(byKey[b.listing])};`,
  );
}
out.push("commit;", "");
process.stdout.write(out.join("\n"));
